// Polls a request until it reaches a status (re-runs itself with setNextRequest).
const poll = (name, idVar, target, maxPolls, after = '') => req(name, {
  path: `/requests/{{${idVar}}}`, who: 'approver',
  pre: `
const n = Number(pm.environment.get('pollCount') || 0);
if (n > 0) { setTimeout(() => {}, 2000); }`,
  test: `
const d = pm.response.json().data;
const n = Number(pm.environment.get('pollCount') || 0) + 1;
if (d.status !== '${target}' && n < ${maxPolls}) {
  pm.environment.set('pollCount', n);
  postman.setNextRequest(pm.info.requestName);
} else {
  pm.environment.set('pollCount', 0);
  console.log('${name}: status=' + d.status + ' attempts=' + d.attempts + ' polls=' + n);
  pm.test('reaches ${target} (status=' + d.status + ', attempts=' + d.attempts + ')', () => pm.expect(d.status).to.eql('${target}'));
${after}
}`,
});

