const s = (code) => code.trim().split('\n');
const auth = (who) => [{ key: 'Authorization', value: `Bearer {{token_${who}}}` }];
const JSONH = [{ key: 'Accept', value: 'application/json' }];
const BODYH = [...JSONH, { key: 'Content-Type', value: 'application/json' }];

function req(name, { method = 'GET', path, who, body, raw, headers = [], pre, test, desc }) {
  const h = [...(body !== undefined || raw !== undefined ? BODYH : JSONH), ...(who ? auth(who) : []), ...headers];
  const item = {
    name,
    request: {
      method,
      header: h,
      url: { raw: `{{baseUrl}}${path}`, host: ['{{baseUrl}}'], path: path.split('?')[0].split('/').filter(Boolean),
        ...(path.includes('?') ? { query: path.split('?')[1].split('&').map((q) => { const [key, value] = q.split('='); return { key, value }; }) } : {}) },
      ...(desc ? { description: desc } : {}),
    },
    event: [],
  };
  if (body !== undefined || raw !== undefined) {
    item.request.body = { mode: 'raw', raw: raw ?? JSON.stringify(body, null, 2), options: { raw: { language: 'json' } } };
  }
  if (pre) item.event.push({ listen: 'prerequest', script: { type: 'text/javascript', exec: s(pre) } });
  if (test) item.event.push({ listen: 'test', script: { type: 'text/javascript', exec: s(test) } });
  return item;
}

